export function photoSource(name: string) {
  if (individualPhotos.has(name)) return { root: 'images/individual/', name };
  if (editorialPhotos.has(name)) return { root: 'images/multicultural/', name };
  return null;
}
export function photoKeyFromUrl(url?: string) {
  const key = url?.match(
    /^\/images\/individual\/([a-z0-9-]+)-(?:640|960|1536)\.(?:avif|webp)$/,
  )?.[1];
  return key && individualPhotos.has(key) ? key : null;
}
